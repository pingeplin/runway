import argparse
import json
import os
import re
import shutil
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import Any, Callable

from _common import (
    BRIEFS_DIR,
    EVAL_ROOT,
    MAX_STATEMENT_CHARS,
    RESULTS_DIR,
    SPEC_SEPARATOR,
    add_config_arg,
    die,
    load_config,
    load_script_module,
    load_split_rows,
    mask_reference_solution,
    read_json,
    read_tasks,
    resolve_path,
    spec_ok_ids,
    write_json,
)

BRIEF_PROMPT = EVAL_ROOT / "prompts" / "brief_headless.md"
HINT_PATH = EVAL_ROOT / "prompts" / "breadth_hint.md"
WORKSPACES_DIR = RESULTS_DIR / "workspaces_brief"
DATASET_DIRS = {
    "A_plan": RESULTS_DIR / "dataset_arm_a_plan",
    "A_hint": RESULTS_DIR / "dataset_arm_a_hint",
}
ARMS = tuple(DATASET_DIRS)

BRIEF_REL = Path(".handoff") / "brief.md"
BRIEF_PATH_RE = re.compile(r"^\s*BRIEF_PATH:\s*(.+?)\s*$", re.MULTILINE)

# The control must not be able to reach blueprint at all. Enforced in code,
# not config, and proven per task from the session's init event.
BLUEPRINT_PLUGIN_ID = "blueprint@runway"
DISABLE_BLUEPRINT = ["--settings", json.dumps({"enabledPlugins": {BLUEPRINT_PLUGIN_ID: False}})]

README_TEMPLATE = """---
configs:
- config_name: default
  data_files:
  - split: {split}
    path: data/{split}.jsonl
---

# Arm {arm} dataset (control arm for the blueprint spec)

Generated by `scripts/14_control_arms.py`. Rows are copied verbatim from
`{dataset}` split `{split}`, except `problem_statement`, which is the original
statement followed by {doc_desc}, under the same separator Arm B uses.

Scoring never reads this directory: `fb eval` runs against the official
dataset and only consumes `instance_id` / `model_patch` from predictions.
"""

DOC_DESC = {
    "A_plan": "a generic implementation brief written with blueprint disabled",
    "A_hint": "the fixed one-sentence breadth hint in `prompts/breadth_hint.md`",
}


def log(msg: str) -> None:
    print(msg, flush=True)


# ------------------------------------------------------------------- brief


def parse_stream(stdout: str) -> tuple[dict[str, Any] | None, dict[str, Any] | None]:
    """(first init event, last result event) of a stream-json transcript."""
    init = result = None
    for line in stdout.splitlines():
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(event, dict):
            continue
        if event.get("type") == "system" and event.get("subtype") == "init" and init is None:
            init = event
        elif event.get("type") == "result":
            result = event
    return init, result


def loaded_extensions(init: dict[str, Any]) -> dict[str, list[str]]:
    plugins = [p.get("name", "") if isinstance(p, dict) else str(p) for p in init.get("plugins") or []]
    return {
        "plugins": plugins,
        "skills": [str(s) for s in (init.get("skills") or []) + (init.get("slash_commands") or [])],
        "agents": [str(a) for a in init.get("agents") or []],
    }


def blueprint_leaks(extensions: dict[str, list[str]]) -> list[str]:
    return sorted({n for names in extensions.values() for n in names if "blueprint" in n.lower()})


def run_claude(
    claude_cmd: str,
    prompt: str,
    workspace: Path,
    model: str,
    claude_args: list[str],
    timeout_s: int,
) -> tuple[dict[str, Any], dict[str, Any] | None, str | None]:
    """One headless pass in stream-json. Returns (result payload, init event, error)."""
    argv = [
        claude_cmd, "-p", prompt, "--output-format", "stream-json", "--verbose",
        *claude_args, *DISABLE_BLUEPRINT, "--model", model,
    ]
    # Same environment as the stage-01 spec writer; see 01_make_specs.run_claude.
    env = {**os.environ, "CLAUDE_CODE_PRINT_BG_WAIT_CEILING_MS": "0"}
    try:
        proc = subprocess.run(
            argv, cwd=workspace, capture_output=True, text=True,
            timeout=timeout_s, env=env,
        )
    except subprocess.TimeoutExpired:
        return {}, None, f"claude timed out after {timeout_s}s"
    except FileNotFoundError:
        return {}, None, f"claude command not found: {claude_cmd}"

    init, result = parse_stream(proc.stdout)
    payload: dict[str, Any] = {"returncode": proc.returncode, **(result or {})}
    if result is None:
        tail = (proc.stderr or proc.stdout or "").strip()[-500:]
        return payload, init, f"no result event in claude stream (rc={proc.returncode}): {tail}"
    if proc.returncode != 0:
        return payload, init, f"claude exited {proc.returncode}"
    return payload, init, None


def locate_brief(workspace: Path, result_text: str) -> tuple[Path | None, str]:
    """BRIEF_PATH marker first, the prompt's fixed path as fallback."""
    matches = BRIEF_PATH_RE.findall(result_text or "")
    if matches:
        candidate = Path(matches[-1].strip().strip("`").strip())
        candidate = candidate if candidate.is_absolute() else workspace / candidate
        if candidate.is_file():
            return candidate, "marker"
    if (workspace / BRIEF_REL).is_file():
        return workspace / BRIEF_REL, "fixed_path"
    return None, "not_found"


def brief_ok(task_id: str) -> bool:
    meta_path = BRIEFS_DIR / f"{task_id}.meta.json"
    if not meta_path.exists() or not (BRIEFS_DIR / f"{task_id}.md").exists():
        return False
    try:
        return bool(read_json(meta_path).get("ok"))
    except (OSError, json.JSONDecodeError):
        return False


def process_brief(
    row: dict[str, Any],
    args: argparse.Namespace,
    brief_cfg: dict[str, Any],
    template: str,
    extract_testbed: Callable[[str, Path, str | None], None],
) -> dict[str, Any]:
    task_id = row["instance_id"]
    workspace = WORKSPACES_DIR / task_id
    meta: dict[str, Any] = {"instance_id": task_id, "image_name": row.get("image_name", "")}

    if workspace.exists():
        shutil.rmtree(workspace)
    try:
        extract_testbed(row.get("image_name", ""), workspace, args.mock_testbed)
    except subprocess.CalledProcessError as exc:
        meta.update(ok=False, error=f"testbed extraction failed: {(exc.stderr or '').strip()[-500:]}")
        return meta

    mask_info = mask_reference_solution(workspace, row)
    meta.update(mask_info)
    if mask_info["mask_applied"] is False or not mask_info["git_reinit"]:
        meta.update(ok=False, error=f"oracle masking incomplete: {mask_info}")
        return meta

    claude_args = list(brief_cfg.get("claude_args", []))
    if brief_cfg.get("max_budget_usd"):
        claude_args += ["--max-budget-usd", str(brief_cfg["max_budget_usd"])]

    started = time.time()
    payload, init, error = run_claude(
        claude_cmd=args.claude_cmd,
        prompt=template.replace("{problem_statement}", row.get("problem_statement", "")),
        workspace=workspace,
        model=brief_cfg.get("model", "claude-sonnet-5"),
        claude_args=claude_args,
        timeout_s=int(brief_cfg.get("timeout_seconds", 3600)),
    )
    meta.update(
        cost_usd=payload.get("total_cost_usd"),
        duration_ms=payload.get("duration_ms"),
        duration_api_ms=payload.get("duration_api_ms"),
        wall_seconds=round(time.time() - started, 2),
        num_turns=payload.get("num_turns"),
        usage=payload.get("usage"),
        returncode=payload.get("returncode"),
        result_subtype=payload.get("subtype"),
    )

    if init is None:
        meta.update(ok=False, error=error or "no init event: cannot prove blueprint was disabled")
        return meta
    extensions = loaded_extensions(init)
    leaks = blueprint_leaks(extensions)
    meta.update(
        claude_code_version=init.get("claude_code_version"),
        plugins_loaded=extensions["plugins"],
        blueprint_leaks=leaks,
    )
    if leaks:
        meta.update(ok=False, error=f"blueprint reachable in the control session: {', '.join(leaks)}")
        return meta
    if error:
        meta.update(ok=False, error=error)
        return meta

    brief_file, how = locate_brief(workspace, payload.get("result") or "")
    if brief_file is None:
        meta.update(ok=False, error=f"no brief produced at {BRIEF_REL}")
        return meta
    text = brief_file.read_text(encoding="utf-8")
    if not text.strip():
        meta.update(ok=False, error=f"brief is empty: {brief_file}")
        return meta

    BRIEFS_DIR.mkdir(parents=True, exist_ok=True)
    dest = BRIEFS_DIR / f"{task_id}.md"
    dest.write_text(text, encoding="utf-8")
    meta.update(
        ok=True,
        error=None,
        brief_located_by=how,
        brief_source=os.path.relpath(brief_file, workspace),
        brief_path=str(dest.relative_to(EVAL_ROOT)),
        brief_chars=len(text),
    )
    if not args.keep_workspaces:
        shutil.rmtree(workspace, ignore_errors=True)
    return meta


def stage_brief(
    task_ids: list[str],
    rows_by_id: dict[str, Any],
    args: argparse.Namespace,
    brief_cfg: dict[str, Any],
) -> int:
    """Write every missing brief. Returns the number of tasks with a usable brief."""
    if not BRIEF_PROMPT.exists():
        die(f"prompt template missing: {BRIEF_PROMPT}")
    template = BRIEF_PROMPT.read_text(encoding="utf-8")
    extract_testbed = load_script_module("01_make_specs.py").extract_testbed
    BRIEFS_DIR.mkdir(parents=True, exist_ok=True)

    def run_one(task_id: str) -> bool:
        if not args.force and brief_ok(task_id):
            log(f"{task_id}: cached brief, skipping")
            return True
        log(f"{task_id}: extracting testbed + writing brief")
        meta = process_brief(rows_by_id[task_id], args, brief_cfg, template, extract_testbed)
        write_json(BRIEFS_DIR / f"{task_id}.meta.json", meta)
        if meta.get("ok"):
            cost = meta.get("cost_usd")
            cost_s = f"${cost:.4f}" if isinstance(cost, (int, float)) else "cost n/a"
            log(f"{task_id}: ok ({cost_s}, {meta['wall_seconds']}s)")
            return True
        log(f"{task_id}: FAILED — {meta.get('error')}")
        return False

    with ThreadPoolExecutor(max_workers=max(1, args.parallel)) as pool:
        return sum(pool.map(run_one, task_ids))


# ----------------------------------------------------------------- dataset


def brief_document(task_id: str) -> str:
    return (BRIEFS_DIR / f"{task_id}.md").read_text(encoding="utf-8").strip()


def hint_document(task_id: str) -> str:
    return HINT_PATH.read_text(encoding="utf-8").strip()


DOCUMENTS: dict[str, Callable[[str], str]] = {"A_plan": brief_document, "A_hint": hint_document}


def stage_dataset(
    arm: str, task_ids: list[str], rows_by_id: dict[str, Any], dataset: str, split: str,
) -> Path:
    stage02 = load_script_module("02_make_dataset.py")
    if arm == "A_plan":
        missing = [i for i in task_ids if not brief_ok(i)]
        if missing:
            die(f"arm A_plan: no usable brief for {', '.join(missing)} — rerun --stage brief")

    out_rows: list[dict[str, Any]] = []
    for task_id in task_ids:
        document = DOCUMENTS[arm](task_id)
        if not document:
            die(f"arm {arm}: empty document for {task_id}")
        row = dict(rows_by_id[task_id])
        row["problem_statement"] = (row.get("problem_statement") or "") + SPEC_SEPARATOR + document
        if len(row["problem_statement"]) > MAX_STATEMENT_CHARS:
            die(f"arm {arm}: {task_id} statement is {len(row['problem_statement'])} chars, "
                f"over the {MAX_STATEMENT_CHARS}-char argv budget")
        out_rows.append(row)

    out_dir = DATASET_DIRS[arm]
    readme = README_TEMPLATE.format(split=split, arm=arm, dataset=dataset, doc_desc=DOC_DESC[arm])
    jsonl_path = stage02.write_dataset(out_rows, split, dataset, out_dir, readme=readme)
    probe = out_rows[0]
    stage02.verify_roundtrip(out_dir, split, len(out_rows), probe["instance_id"], probe["problem_statement"])
    log(f"arm {arm} dataset: {len(out_rows)} row(s) -> {jsonl_path}")
    return out_dir


# ------------------------------------------------------------- infer + eval


def stage_infer(arm: str, cfg: dict, task_ids: list[str], dry_run: bool) -> int:
    dataset_dir = DATASET_DIRS[arm]
    if not (dataset_dir / "README.md").exists():
        die(f"arm {arm} dataset missing at {dataset_dir} — run --stage dataset first")
    stage03 = load_script_module("03_infer.py")
    return stage03.run_arm(arm, cfg, task_ids, dry_run, dataset=str(dataset_dir))


def stage_eval(arm: str, cfg: dict, task_ids: list[str], dry_run: bool) -> int:
    stage04 = load_script_module("04_eval.py")
    return stage04.run_arm(arm, cfg, cfg["_fb_config_path"], task_ids, dry_run)


# -------------------------------------------------------------------- main


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    add_config_arg(parser)
    parser.add_argument("--stage", choices=["brief", "dataset", "infer", "eval", "all"], default="all")
    parser.add_argument("--arm", choices=[*ARMS, "both"], default="both",
                        help="Which control arm the dataset/infer/eval stages cover")
    parser.add_argument("--parallel", type=int, default=1, help="Concurrent brief workers (claude -p sessions)")
    parser.add_argument("--force", action="store_true", help="Redo tasks whose brief already succeeded")
    parser.add_argument("--dry-run", action="store_true", help="Print the fb infer/eval commands without running them")
    parser.add_argument("--claude-cmd", default="claude", help="Path to the claude binary (for smoke tests)")
    parser.add_argument("--mock-testbed", default=None, help="Copy this dir instead of docker cp (for smoke tests)")
    parser.add_argument("--mock-dataset", default=None, help="Read rows from this JSONL instead of HuggingFace")
    parser.add_argument("--keep-workspaces", action="store_true",
                        help="Keep results/workspaces_brief/<id>/ after a successful brief")
    args = parser.parse_args()

    cfg = load_config(args.config)
    eval_cfg = cfg.get("eval", {})
    # [brief] mirrors [spec]; anything it omits (notably claude_args) falls
    # back to [spec], so the control writer runs exactly like the spec writer.
    brief_cfg = {**cfg.get("spec", {}), **cfg.get("brief", {})}
    dataset = eval_cfg.get("dataset", "")
    split = eval_cfg.get("split", "lite")
    arms = list(ARMS) if args.arm == "both" else [args.arm]
    stages = ["brief", "dataset", "infer", "eval"] if args.stage == "all" else [args.stage]

    fb_config = resolve_path(str(cfg.get("infer", {}).get("fb_config_path", "fb_config.toml")))
    if {"infer", "eval"} & set(stages) and not args.dry_run and not fb_config.exists():
        die(f"fb config not found: {fb_config} (copy fb_config.example.toml)")
    cfg["_fb_config_path"] = fb_config

    task_ids = sorted(spec_ok_ids(read_tasks()))
    if not task_ids:
        die("no spec_ok tasks in results/tasks.json — the control arms run on the stage-01 panel")

    rows_by_id: dict[str, Any] = {}
    if {"brief", "dataset"} & set(stages):
        rows_by_id = {r["instance_id"]: r for r in load_split_rows(dataset, split, args.mock_dataset)}
        missing = [i for i in task_ids if i not in rows_by_id]
        if missing:
            die(f"task ids absent from {dataset}:{split}: {', '.join(missing)}")

    if "brief" in stages:
        n_ok = stage_brief(task_ids, rows_by_id, args, brief_cfg)
        log(f"stage 14 brief: {n_ok}/{len(task_ids)} briefs ok -> {BRIEFS_DIR}")
        if n_ok < len(task_ids):
            print("error: A_plan needs a brief for every panel task; rerun --stage brief "
                  "(cached briefs are skipped)")
            return 1

    if "dataset" in stages:
        for arm in arms:
            stage_dataset(arm, task_ids, rows_by_id, dataset, split)

    for stage, run in (("infer", stage_infer), ("eval", stage_eval)):
        if stage in stages:
            for arm in arms:
                rc = run(arm, cfg, task_ids, args.dry_run)
                if rc != 0:
                    return rc
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
