#!/usr/bin/env python3
"""Stage 14 — control arms: is Arm B's lift blueprint's, or anyone's?

Arm B (original + blueprint spec) lifted pass rate 0.42 -> 0.84 on the clean
astropy panel. The A/B pair cannot tell that apart from two cheaper stories,
so this stage adds one arm per story on the same panel:

  A_plan  original + an implementation brief written by the same model, in
          the same masked workspace, with the blueprint plugin disabled and
          no prescribed structure — "any upfront document does this"
  A_hint  original + one fixed sentence naming the breadth mechanism the 4.0
          specs carried — "the lift is one sentence"

Stages:
  brief    per task: extract and mask the testbed exactly as stage 01 does,
           then run headless `claude -p` with prompts/brief_headless.md and
           blueprint disabled through --settings. The session's init event
           must list no blueprint plugin, skill or agent, or the task fails.
           Brief + meta land in results/briefs/.
  dataset  results/dataset_arm_a_plan/ and results/dataset_arm_a_hint/, whose
           problem_statement is original + SPEC_SEPARATOR + brief | hint
  infer    `fb infer` per arm, recorded in results/runs.json
  eval     `fb eval` per arm against the OFFICIAL dataset

Both arms cover the stage-01 panel (tasks.json spec_ok ids), so every cell
pairs with A and B. A panel task without a usable brief fails the dataset
stage rather than silently shrinking A_plan.
"""

