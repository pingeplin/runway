DATASET_DIRS = {"C": RESULTS_DIR / "dataset_arm_c", "C0": RESULTS_DIR / "dataset_arm_c0"}

# Where the referee finds the spec inside the scratch workspace. One file, one
# fixed path: the verify skill otherwise picks "the most recently modified spec".
WORKSPACE_SPEC_REL = Path(".blueprint") / "specs" / "spec.md"

VERDICT_PATH_RE = re.compile(r"^\s*VERDICT_PATH:\s*(.+?)\s*$", re.MULTILINE)

# The one region that differs between C and C0. Everything around it — the
# previous-attempt block and the repair instruction — is byte-identical.
VERDICT_BLOCK = "## Referee verdict\n\n{verdict}"
CONTROL_BLOCK = (
    "## Self-review\n\n"
    "Review the previous attempt critically yourself and correct any flaws you find."
)

