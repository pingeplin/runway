#!/usr/bin/env python3
"""Stage 06 — Arm C: does blueprint's `/verify` referee add value on top of the spec?

Round 1 is Arm B's existing patch (stage 03). This stage adds:

  verify   for each task, take a FRESH copy of the stage-01 workspace, apply
           Arm B's `model_patch` into it, drop the spec at a canonical path and
           run headless `claude -p` with the blueprint `verify` skill. The
           referee cannot run the test suite (deps live in docker), so the
           prompt restricts it to static checks. Verdict + cost/duration meta
           land in results/verdicts/.
  dataset  build two round-2 datasets whose problem_statement is
           original + spec + previous patch + feedback + repair instruction:
             C   feedback = the referee verdict
             C0  feedback = "review it yourself" (control for the mere
                 second-iteration effect — same N, same everything else)
  infer    `fb infer` per arm, recorded in results/runs.json under "C" / "C0"
  eval     `fb eval` per arm against the OFFICIAL dataset (stage 04 only knows
           arms A/B, so C/C0 are scored from here)

C and C0 are always built from the SAME task-id list — a task that has no Arm B
patch, or whose verify round failed, is dropped from both.
"""

