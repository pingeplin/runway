#!/usr/bin/env python3
"""Stage 02 — build Arm B's local dataset: problem_statement + spec.

Writes a HuggingFace dataset directory that `datasets.load_dataset(<dir>,
split=<split>)` — and therefore `fb infer --dataset <dir> --split <split>` —
accepts unchanged. Every column of the official row is preserved verbatim;
only `problem_statement` is rewritten, and only for tasks whose spec stage
succeeded. The result is round-tripped in-process before the script exits.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from _common import (
    RESULTS_DIR,
    SPECS_DIR,
    SPEC_SEPARATOR,
    add_config_arg,
    die,
    load_config,
    load_split_rows,
    read_tasks,
    spec_ok_ids,
)

OUT_DIR = RESULTS_DIR / "dataset_arm_b"

# `datasets` >= 3 resolves a local directory through the README front-matter
# `configs:` block; this is what lets an arbitrary split name like "lite" work.
README_TEMPLATE = """---
configs:
- config_name: default
  data_files:
  - split: {split}
    path: data/{split}.jsonl
---

# Arm B dataset (blueprint spec ablation)

Generated by `scripts/02_make_dataset.py`. Rows are copied verbatim from
`{dataset}` split `{split}`, except `problem_statement`, which is the original
statement followed by the blueprint spec produced in stage 01.

Scoring never reads this directory: `fb eval` runs against the official
dataset and only consumes `instance_id` / `model_patch` from predictions.
"""


def write_dataset(rows: list[dict[str, Any]], split: str, dataset: str, out_dir: Path) -> Path:
    data_dir = out_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    jsonl_path = data_dir / f"{split}.jsonl"
    with open(jsonl_path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    (out_dir / "README.md").write_text(
        README_TEMPLATE.format(split=split, dataset=dataset), encoding="utf-8"
    )
    return jsonl_path


def purge_stale_cache(out_dir: Path) -> None:
    # HF `datasets` keys the prepared-dataset cache by the directory BASENAME,
    # so any previous dataset written to a same-named dir (e.g. the smoke
    # test's fixture) can shadow this one — worst case `fb infer` silently
    # reads stale rows. Drop the cache entry before the verification load
    # regenerates it from the files just written.
    import shutil

    from datasets import config as ds_config

    cache_root = Path(ds_config.HF_DATASETS_CACHE)
    basename = out_dir.name
    for path in [cache_root / basename, *cache_root.glob(f"*_{basename}_*.lock")]:
        if path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
        elif path.exists():
            path.unlink(missing_ok=True)


def verify_roundtrip(out_dir: Path, split: str, expect_rows: int, probe_id: str, probe_text: str) -> None:
    try:
        from datasets import load_dataset
    except ImportError:
        die("the `datasets` library is required: pip install datasets")

    purge_stale_cache(out_dir)
    ds = load_dataset(str(out_dir), split=split)
    if len(ds) != expect_rows:
        die(f"round-trip failed: loaded {len(ds)} rows, expected {expect_rows}")
    by_id = {r["instance_id"]: r for r in ds}
    if probe_id not in by_id:
        die(f"round-trip failed: {probe_id} missing from reloaded dataset")
    if by_id[probe_id]["problem_statement"] != probe_text:
        die(f"round-trip failed: problem_statement of {probe_id} did not survive the write")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    add_config_arg(parser)
    parser.add_argument("--mock-dataset", default=None, help="Read rows from this JSONL instead of HuggingFace")
    parser.add_argument("--out-dir", default=None, help="Override the output dataset directory")
    args = parser.parse_args()

    cfg = load_config(args.config)
    eval_cfg = cfg.get("eval", {})
    dataset = eval_cfg.get("dataset", "")
    split = eval_cfg.get("split", "lite")
    out_dir = Path(args.out_dir).resolve() if args.out_dir else OUT_DIR

    tasks = read_tasks()
    ok_ids = spec_ok_ids(tasks)
    if not ok_ids:
        die("no spec_ok tasks in results/tasks.json — run stage 01 first")

    rows = load_split_rows(dataset, split, args.mock_dataset)
    by_id = {r["instance_id"]: r for r in rows}
    missing = [i for i in ok_ids if i not in by_id]
    if missing:
        die(f"spec_ok ids absent from {dataset}:{split}: {', '.join(missing)}")

    out_rows: list[dict[str, Any]] = []
    probe_id = probe_text = ""
    for task_id in sorted(ok_ids):
        spec_file = SPECS_DIR / f"{task_id}.md"
        if not spec_file.exists():
            die(f"spec marked ok but missing on disk: {spec_file}")
        spec_text = spec_file.read_text(encoding="utf-8").strip()
        if not spec_text:
            die(f"spec is empty: {spec_file}")

        row = dict(by_id[task_id])
        row["problem_statement"] = (row.get("problem_statement") or "") + SPEC_SEPARATOR + spec_text
        out_rows.append(row)
        if not probe_id:
            probe_id, probe_text = task_id, row["problem_statement"]

    jsonl_path = write_dataset(out_rows, split, dataset, out_dir)
    verify_roundtrip(out_dir, split, len(out_rows), probe_id, probe_text)

    print(f"stage 02 ok: {len(out_rows)} row(s) -> {jsonl_path}")
    print(f"  load with: datasets.load_dataset('{out_dir}', split='{split}')")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
